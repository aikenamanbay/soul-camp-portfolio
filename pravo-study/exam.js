function addedExamQuestions(group, language) {
 const localeIndex = language === 'kk' ? 2 : 1;
 return examAdditions[group].map((entry, index) => {
  const [prompt, a, b, c, explanation] = entry[localeIndex];
  return {
   id: group+':extra-'+(group === 'theory' ? index+1 : index),
   topic: group,
   q: [prompt, [a, b, c], entry[0], explanation]
  };
 });
}

function makeExamGroups(topics, language) {
 return topics.map(topic => {
  if (topic.id === 'family') return {...topic, questions: familyLessonQuestions(language)};
  if (topic.id === 'civil') return {...topic, questions: civilLessonQuestions(language)};
  const original = topic.quiz.map((q, index) => ({q, id: topic.id+':'+index, topic: topic.id}));
  const questions = topic.id === 'theory' ? original.slice(3) : original;
  return {...topic, questions: [...questions, ...addedExamQuestions(topic.id, language)]};
 });
}
