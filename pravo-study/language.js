function translateUi(value) {
 const trimmed = value.trim();
 if (!trimmed) return value;
 let translated = Object.hasOwn(uiKazakh, trimmed) ? uiKazakh[trimmed] : trimmed;
 if (trimmed.endsWith(' ↗') && sourceNames[trimmed.slice(0,-2)]) translated = sourceNames[trimmed.slice(0,-2)]+' ↗';
 if (translated === trimmed) {
  for (const [pattern, replacement] of uiPatterns) {
   if (pattern.test(trimmed)) { translated = trimmed.replace(pattern, replacement); break; }
  }
 }
 return value.replace(trimmed, () => translated);
}
function translateView(root) {
 const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
 while (walker.nextNode()) walker.currentNode.data = translateUi(walker.currentNode.data);
 for (const item of [root, ...root.querySelectorAll('[aria-label]')]) {
  if (item.hasAttribute('aria-label')) item.setAttribute('aria-label',translateUi(item.getAttribute('aria-label')));
 }
}
